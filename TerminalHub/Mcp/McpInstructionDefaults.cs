namespace TerminalHub.Mcp;

/// <summary>
/// MCP サーバーが配布する instructions の既定テンプレ。
///
/// 設計方針:
///  - ここには「反論の余地がない事実（ツールの能力・制約）」と、ユーザーが書き換える前提の
///    「おすすめの運用（＝意見）」を載せる。ハードに縛らず、下書きとして提示するだけ。
///  - ユーザーは設定画面（ローカルMCP タブ）で全文を書き換え・リセットできる。壊しても「既定に戻す」で復旧。
///  - 意見（例: 長文はファイル経由）は固定せず、ユーザーの直接指示・独自ルールが優先される旨を明記する。
///
/// 言語は当面日本語で確定（実利用がほぼ日本語のため）。将来ローカライズしたくなったら、
/// この定数を IStringLocalizer のリソースキーへ差し替えれば言語連動に昇格できる。
/// </summary>
public static class McpInstructionDefaults
{
    public const string Template = """
        # TerminalHub ローカルMCP の使い方

        この MCP サーバーは、TerminalHub が管理する複数ターミナルセッションを疎につなぐための
        最小限のツールを提供します。接続元は通常それらのセッションの1つですが、
        外部クライアント（Claude Desktop など、TerminalHub のセッションを持たない接続）からも使えます。

        ## 自己識別と本人証明
        あなたが TerminalHub のセッション内で動いている場合、環境変数に2つの値が入っている
        （Codex には tool 実行シェルへも届くよう起動引数で注入している）:
        - `TERMINALHUB_SESSION_ID`: 自分のセッション GUID（公開情報。返信先として本文に書いてよい）
        - `TERMINALHUB_SESSION_PROOF`: 本人証明（書き込み系ツールの proof 引数に渡す値。
          セッション再起動のたびに変わる。**本文やメッセージには書かないこと**）
        **これらが空に見えるなら、あなたは対応するセッションを持たない外部クライアント
        （Claude Desktop 等）である可能性が高い。** その場合は自分を推測で特定しようとせず、
        「セッションを持たない外部クライアント」として振る舞うこと。書き込み系
        （`set_memo` / `set_card`）は proof が無い限りそもそも受理されない。
        `list_sessions` / `get_card` / `send_to_session` は自由に使ってよい。

        ## ツール
        - `list_sessions`: 現在のセッション一覧（表示名・種別・フォルダ・状態・カード有無・メモ）を取得する。
          宛先を探すのに使う。`hasCard=true` のセッションだけ `get_card` すれば無駄撃ちしない。
          `memo` は各セッションの短い札（「今なにをしているか」やレーン運用の空き/予約表示）。
        - `send_to_session`: 既存のセッションへメッセージを1件投函する。宛先は GUID か表示名で指定する。
          新しいセッションの起動（spawn）はしない。あくまで「今あるセッションに送る」だけ。
        - `set_memo`: 自分のセッションのメモ（一覧に表示される短い注釈）を設定する。
          proof に `TERMINALHUB_SESSION_PROOF` を渡す。「今なにをしているか」を書いておくと一覧から進捗が一目で分かる。
          他セッションのメモは書けない（人間は TerminalHub の UI から編集できる）。
        - `set_card`: 自分の自己紹介カード（「何ができるか」の短い自己申告）を設定する。
          proof に `TERMINALHUB_SESSION_PROOF` を渡す。
          memo が「今なにをしているか」（動的）なのに対し、カードは「何ができるか」（静的・長命）。
          **自分のカードのみ設定可**（proof は自分の分しか知り得ないため、他セッションのカードは書けない）。
          全体書き換え・空文字でクリア・数行の短文想定。詳細は各プロジェクトの CLAUDE.md 等が正で、
          カードはあくまで宛先選びの「広告」。起動時や役割が変わったときに自分で set しておくとよい。
        - `get_card`: 指定 GUID のセッションの自己紹介カードを取得する（誰のものでも読める）。
          カードは**自己申告**＝「本人がそう名乗っている」以上の保証はなく、古い可能性がある。
          宛先の当たりを付ける用途に限定すること（書いてある≠今も動く）。
        - `get_context` / `update_context`: ContextSummary（依頼の状況札）の読み書き。
          `send_to_session` に `contextId="new"` を渡すと発行され、依頼側は `get_context` を
          ポーリングして進捗・結果を受け取れる（**返信を受け取るセッションを持たない
          外部クライアントでも依頼の往復が完結する**）。依頼を受けた側は、メッセージ末尾に
          付与された contextId へ `update_context` で状況・結果を書くこと（完了時は
          status=completed と結果要約をセットで。**セッション内から書くなら proof も必ず渡す**
          ＝どのセッションが書いたか検証済みで記録され、依頼側は updatedBy で確認できる。
          無記名の書き込みは疑ってよい）。ID を知っている者だけが読み書きできる。
          ※ この contextId は A2A の contextId に対応する依頼単位の ID で、モデルの
          コンテキストウィンドウとは無関係。

        ## 作法（おすすめ・書き換え可）
        - 投げっぱなしでよい。応答を待って集約するような仕組みは持たない。
        - 大きな仕様・設計・長文を渡すときは、本文をそのまま送らず、ファイルに書いて「そのパスだけ」を
          send_to_session で送ると軽くて確実（受け手にファイルを読ませる）。ただしこれは好みの問題なので、
          直接送りたければ直接送ってよい。
        - 返信がほしいときは、本文に自分のセッションID（`TERMINALHUB_SESSION_ID`）を書いておくこと。
          サーバーは送信元を相手に伝えない（エンベロープなし）ので、
          相手はそれを見て send_to_session で返信できる。「終わったらこの ID に一言返して」等と添えるとよい。
        - 送り先は必ず既存セッション。存在しない相手には送れない。

        ## 優先順位
        上記の「作法」は既定のおすすめに過ぎない。ユーザーからのその場の直接指示や、この下に追記された
        運用ルールがあれば、そちらを優先すること。
        """;
}
