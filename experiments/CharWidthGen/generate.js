// CharWidth.cs 自動生成スクリプト
//
// xterm.js の Unicode11Addon（ビルド済み dist）から全コードポイントの wcwidth を実測ダンプし、
// それと完全一致する C# テーブル（TerminalHub.Terminal/CharWidth.cs）と
// パリティテスト用フィクスチャ（TerminalHub.Terminal.Tests/Fixtures/u11-widths.json）を生成する。
//
// 幅の意見が xterm と食い違うと、切替時の再生（エミュレータのシリアライズ → xterm へ流し込み）で
// レイアウトが崩れるため、C# 側の幅テーブルは手書きせず必ずここから生成する。
//
// 使い方:
//   1. wwwroot が読み込んでいるのと同じバージョンの addon-unicode11.js を用意する
//      （App.razor の CDN URL と同じもの。例: https://cdn.jsdelivr.net/npm/@xterm/addon-unicode11@0.9.0/lib/addon-unicode11.js）
//   2. node generate.js <addon-unicode11.jsのパス> <リポジトリルート>
//
// 出力:
//   <root>/TerminalHub.Terminal/CharWidth.cs
//   <root>/TerminalHub.Terminal.Tests/Fixtures/u11-widths.json

const fs = require('fs');
const path = require('path');

const [addonPath, repoRoot] = process.argv.slice(2);
if (!addonPath || !repoRoot) {
    console.error('usage: node generate.js <addon-unicode11.js> <repo-root>');
    process.exit(1);
}

// UMD ビルドは CommonJS としてそのまま require できる。
// activate はプロバイダ（UnicodeV11）を register するだけなので、スタブ terminal で捕まえる
const addonModule = require(path.resolve(addonPath));
const cap = { provider: null };
new (addonModule.Unicode11Addon)().activate({ unicode: { register: (p) => { cap.provider = p; } } });
const wcwidth = (cp) => cap.provider.wcwidth(cp);

// 全コードポイントを RLE ダンプ
const ranges = [];
let curW = -1, start = 0;
for (let cp = 0; cp <= 0x10FFFF; cp++) {
    const w = wcwidth(cp);
    if (w !== curW) {
        if (curW >= 0) ranges.push([start, cp - 1, curW]);
        curW = w;
        start = cp;
    }
}
ranges.push([start, 0x10FFFF, curW]);

const fixturePath = path.join(repoRoot, 'TerminalHub.Terminal.Tests', 'Fixtures', 'u11-widths.json');
fs.writeFileSync(fixturePath, JSON.stringify(ranges));
console.log(`fixture: ${fixturePath} (${ranges.length} ranges)`);

// C# コード生成
const bmpZero = [], bmpWide = [], astralZero = [], astralWide = [];
for (const [s, e, w] of ranges) {
    if (w === 1) continue;
    const bucketBmp = w === 0 ? bmpZero : bmpWide;
    const bucketAstral = w === 0 ? astralZero : astralWide;
    if (s < 0x10000) {
        bucketBmp.push([s, Math.min(e, 0xFFFF)]);
    }
    if (e >= 0x10000) {
        bucketAstral.push([Math.max(s, 0x10000), e]);
    }
}

function emitPairs(pairs, indent) {
    const lines = [];
    for (let i = 0; i < pairs.length; i += 6) {
        lines.push(indent + pairs.slice(i, i + 6)
            .map(([s, e]) => `0x${s.toString(16).toUpperCase()}, 0x${e.toString(16).toUpperCase()},`)
            .join(' '));
    }
    return lines.join('\n');
}

const cs = `namespace TerminalHub.Terminal;

// <auto-generated>
// このファイルは experiments/CharWidthGen/generate.js による自動生成。手編集しないこと。
// 生成元: @xterm/addon-unicode11@0.9.0 の wcwidth（wwwroot が読み込んでいるものと同一バージョン）
// </auto-generated>

/// <summary>
/// コードポイントの表示セル幅。0=結合文字等, 1=半角, 2=全角。
/// xterm.js の Unicode11Addon の wcwidth と全コードポイントで完全一致させた自動生成テーブル。
/// 幅の意見が xterm と食い違うと切替時の再生でレイアウトが崩れるため、
/// 変更は必ず experiments/CharWidthGen/generate.js の再実行で行う
/// （全点パリティは CharWidthParityTests が Fixtures/u11-widths.json と突き合わせて担保する）。
/// VS16（U+FE0F）による拡幅はここでは扱わない（幅0を返し、VtParser → TerminalGrid.ApplyVs16 が処理する）。
/// </summary>
public static class CharWidth
{
    /// <summary>コードポイントの表示セル幅を返す。</summary>
    public static int GetWidth(int cp)
    {
        if (cp < 0)
        {
            return 1;
        }
        if (cp < 0x10000)
        {
            return Bmp[cp];
        }
        if (cp > 0x10FFFF)
        {
            return 1;
        }
        if (InRanges(cp, AstralZero))
        {
            return 0;
        }
        return InRanges(cp, AstralWide) ? 2 : 1;
    }

    private static byte[] BuildBmp()
    {
        var table = new byte[0x10000];
        Array.Fill(table, (byte)1);
        for (int i = 0; i < BmpZero.Length; i += 2)
        {
            for (int cp = BmpZero[i]; cp <= BmpZero[i + 1]; cp++)
            {
                table[cp] = 0;
            }
        }
        for (int i = 0; i < BmpWide.Length; i += 2)
        {
            for (int cp = BmpWide[i]; cp <= BmpWide[i + 1]; cp++)
            {
                table[cp] = 2;
            }
        }
        return table;
    }

    /// <summary>[start, end] のフラット配列に対する二分探索。</summary>
    private static bool InRanges(int cp, int[] ranges)
    {
        int lo = 0, hi = ranges.Length / 2 - 1;
        while (lo <= hi)
        {
            int mid = (lo + hi) / 2;
            if (cp > ranges[mid * 2 + 1])
            {
                lo = mid + 1;
            }
            else if (cp < ranges[mid * 2])
            {
                hi = mid - 1;
            }
            else
            {
                return true;
            }
        }
        return false;
    }

    // ---- 生成データ（[start, end] のフラット配列） ----
    // 注意: C# の静的フィールドは宣言順に初期化されるため、
    // Bmp（BuildBmp がこれらを参照する）より必ず先に宣言すること


    private static readonly int[] BmpZero =
    {
${emitPairs(bmpZero, '        ')}
    };

    private static readonly int[] BmpWide =
    {
${emitPairs(bmpWide, '        ')}
    };

    private static readonly int[] AstralZero =
    {
${emitPairs(astralZero, '        ')}
    };

    private static readonly int[] AstralWide =
    {
${emitPairs(astralWide, '        ')}
    };

    /// <summary>BMP は表引き（Unicode11Addon と同じ方式）。静的初期化で一度だけ構築する。</summary>
    private static readonly byte[] Bmp = BuildBmp();
}
`;

const csPath = path.join(repoRoot, 'TerminalHub.Terminal', 'CharWidth.cs');
fs.writeFileSync(csPath, cs.replace(/\n/g, '\r\n'));
console.log(`generated: ${csPath} (bmpZero=${bmpZero.length}, bmpWide=${bmpWide.length}, astralZero=${astralZero.length}, astralWide=${astralWide.length})`);
